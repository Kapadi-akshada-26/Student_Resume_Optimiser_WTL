function buildLookup() {
  const lookup = new Map();
  for (const [canonical, synonyms] of Object.entries(CANONICAL_TO_SYNONYMS)) {
    const label = canonical.replace(/_/g, ' ');
    lookup.set(canonical, label);
    lookup.set(label, label);
    for (const syn of synonyms) {
      lookup.set(String(syn).toLowerCase(), label);
    }
  }
  return lookup;
}

const SKILL_LOOKUP = buildLookup();
const CANONICAL_SKILLS = [...new Set(Object.keys(CANONICAL_TO_SYNONYMS).map((k) => k.replace(/_/g, ' ')))];

function resolveSkill(token) {
  if (!token) return null;
  const key = String(token).toLowerCase().trim();
  if (!key) return null;
  return SKILL_LOOKUP.get(key) || null;
}

